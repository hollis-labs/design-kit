import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true })
const results = []
const enter = async locator => { await locator.focus(); await locator.press('Enter') }
const space = async locator => { await locator.focus(); await locator.press('Space') }
try {
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } })
    const errors = [], requests = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (r.resourceType() === 'fetch' || r.resourceType() === 'xhr') requests.push(r.url()) })
    await page.goto(process.env.FIXTURE_URL || 'http://127.0.0.1:18755')
    const wizard = page.getByRole('region', { name: 'Nanite wizard', exact: true })
    const next = () => wizard.getByRole('button', { name: 'Next', exact: true })
    await wizard.getByText('Connectivity check: Not reported', { exact: true }).waitFor()
    assert.equal(await wizard.getByText('Connectivity check: OK', { exact: true }).count(), 0)
    const orderBefore = await wizard.getByRole('list', { name: 'Setup steps' }).getByRole('listitem').allTextContents()
    await space(wizard.getByRole('checkbox', { name: 'Developer mode (required)' }))
    const orderAfter = await wizard.getByRole('list', { name: 'Setup steps' }).getByRole('listitem').allTextContents()
    assert.deepEqual(orderAfter.map(s => s.split(' — ')[0]), orderBefore.map(s => s.split(' — ')[0]))
    assert.equal(await next().isDisabled(), true, 'host-required idle check not reported OK')
    await enter(wizard.getByRole('button', { name: 'Request connectivity check' }))
    await enter(next())
    const context = wizard.getByLabel('Listen address (required)', { exact: true })
    assert.equal(await context.evaluate(el => el.tagName), 'OUTPUT')
    assert.equal(await wizard.locator('input, select').count(), 0)
    assert.equal(await context.innerText(), '127.0.0.1:8090')
    assert.equal(await context.evaluate(el => getComputedStyle(el).fontSize), '13px')
    await enter(next())
    const secret = wizard.getByLabel('API token (required)', { exact: true })
    assert.equal(await secret.inputValue(), '')
    assert.equal(await next().isDisabled(), true, 'absent required secret blocks Next')
    const style = await secret.evaluate(el => ({ font: getComputedStyle(el).fontSize, radius: getComputedStyle(el).borderRadius }))
    assert.deepEqual(style, { font: '13px', radius: '6px' })
    const panelRadius = await wizard.getByRole('form').evaluate(el => getComputedStyle(el).borderRadius)
    assert.equal(panelRadius, '10px')
    await secret.focus()
    await page.keyboard.type('temporary')
    await page.keyboard.press('ControlOrMeta+A')
    await page.keyboard.press('Backspace')
    assert.equal(await next().isDisabled(), true, 'deliberate invalid required replacement blocks Next')
    assert.equal(await secret.getAttribute('aria-invalid'), 'true')
    await page.keyboard.type('ephemeral-wizard-secret')
    await space(page.getByRole('checkbox', { name: 'Fail wizard checks in demo host', exact: true }))
    await enter(wizard.getByRole('button', { name: 'Request connectivity check' }))
    assert.equal(await next().isDisabled(), true)
    await wizard.getByText('Connectivity check: Failed', { exact: true }).waitFor()
    assert.equal(await wizard.getByText('Connectivity check: OK', { exact: true }).count(), 0)
    await space(page.getByRole('checkbox', { name: 'Fail wizard checks in demo host', exact: true }))
    await enter(wizard.getByRole('button', { name: 'Request connectivity check' }))
    await enter(next())
    const reviewSecret = wizard.getByRole('region', { name: 'Review Example notifier (hypothetical plugin)', exact: true })
    const reviewPreferences = wizard.getByRole('region', { name: 'Review Preferences', exact: true })
    await reviewSecret.getByText('API token: will be replaced', { exact: true }).waitFor()
    assert.equal((await wizard.innerText()).includes('ephemeral-wizard-secret'), false)
    assert.equal(await wizard.getByText('Save result: Saved', { exact: true }).count(), 0)
    assert.equal(await wizard.getByText('Save result: Not reported', { exact: true }).count(), 3)
    await space(page.getByRole('checkbox', { name: 'Fail wizard secret saves in demo host', exact: true }))
    await enter(wizard.getByRole('button', { name: 'Submit setup', exact: true }))
    await reviewPreferences.getByText('Save result: Saved', { exact: true }).waitFor()
    await reviewSecret.getByText('Save result: Failed', { exact: true }).waitFor()
    assert.ok(await reviewSecret.getByText('API token: will be replaced', { exact: true }).count())
    assert.equal(await page.getByText('Wizard submit count: 1', { exact: true }).count(), 1)
    // Host-controlled resume: same step + draft, without storage or network.
    await enter(page.getByRole('button', { name: 'Resume Nanite secret step', exact: true }))
    assert.equal(await wizard.getByLabel('API token (required)', { exact: true }).inputValue(), 'ephemeral-wizard-secret')
    await enter(next())
    await space(page.getByRole('checkbox', { name: 'Fail wizard secret saves in demo host', exact: true }))
    await enter(wizard.getByRole('button', { name: 'Submit setup', exact: true }))
    await reviewSecret.getByText('Save result: Saved', { exact: true }).waitFor()
    assert.equal(await page.getByText('Wizard submit count: 2', { exact: true }).count(), 1)
    await enter(wizard.getByRole('button', { name: 'Back', exact: true }))
    assert.equal(await wizard.getByLabel('API token (required)', { exact: true }).inputValue(), '')
    // Complete the second authored manifest entirely through keyboard actions.
    const other = page.getByRole('region', { name: 'Tachyon wizard', exact: true })
    const url = other.getByLabel('Nanite API URL', { exact: true })
    await url.focus(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.press('Backspace')
    assert.equal(await other.getByRole('button', { name: 'Next', exact: true }).isDisabled(), true)
    await page.keyboard.type('http://wizard.example')
    await enter(other.getByRole('button', { name: 'Request connectivity check' }))
    await enter(other.getByRole('button', { name: 'Next', exact: true }))
    await enter(other.getByRole('button', { name: 'Submit setup', exact: true }))
    await other.getByText('Save result: Saved', { exact: true }).waitFor()
    const bounds = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }))
    assert.ok(bounds.scroll <= bounds.viewport)
    assert.deepEqual(errors, []); assert.deepEqual(requests, [])
    results.push({ width, style, panelRadius, readonlyContextFont: '13px', orderBefore, orderAfter, staticOrder: true, invalidRequiredNextBlocked: true, unreportedCheckNeverOK: true, failedBlockingCheckBlocksNext: true, secretReviewRedacted: true, hostResumePreservesDraft: true, partialSavedFailedTruthful: true, manualRetry: true, successfulSecretClearedByHost: true, keyboardOnlyCompletionBothManifests: true, bounds, pageErrors: errors, networkChecks: requests, accessibility: await wizard.ariaSnapshot() })
    await page.close()
  }
  const receipt = { fixture: 'packages/kit-settings/demo/wizard-demo.tsx', engine: browser.version(), scope: 'Actual keyboard actions and browser semantics; no live screen-reader speech or real app/backend connectivity.', results }
  if (process.argv[2]) await writeFile(process.argv[2], JSON.stringify(receipt, null, 2) + '\n')
  console.log(JSON.stringify(receipt, null, 2))
} finally { await browser.close() }
