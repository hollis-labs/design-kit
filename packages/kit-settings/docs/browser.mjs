import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true })
const results = []
try {
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(process.env.FIXTURE_URL || 'http://127.0.0.1:18755')
    const preferences = page.getByRole('form', { name: 'Preferences', exact: true })
    const deployment = page.getByRole('form', { name: 'Deployment configuration', exact: true })
    const connections = page.getByRole('form', { name: 'Observation connections', exact: true })
    const secretForm = page.getByRole('form', { name: 'Example notifier (hypothetical plugin)', exact: true })
    const input = page.getByLabel('Nanite API URL', { exact: true })
    const select = preferences.getByRole('combobox', { name: 'Tool stream behavior (required)' })
    const styles = await input.evaluate(el => {
      const c = getComputedStyle(el), root = getComputedStyle(document.documentElement)
      return { fontSize: c.fontSize, token: root.getPropertyValue('--text-control').trim(), color: c.color, borderRadius: c.borderRadius }
    })
    assert.equal(styles.fontSize, '13px')
    assert.ok(styles.token, 'text-control token is defined')
    assert.equal(styles.borderRadius, '6px')
    assert.equal(await select.evaluate(el => getComputedStyle(el).fontSize), '13px')
    assert.equal(await connections.evaluate(el => getComputedStyle(el).borderRadius), '10px')
    const saveStyle = await connections.getByRole('button', { name: 'Save changes', exact: true }).evaluate(el => ({ font: getComputedStyle(el).fontSize, radius: getComputedStyle(el).borderRadius }))
    assert.deepEqual(saveStyle, { font: '13px', radius: '6px' })
    // Actual keyboard actions on native checkbox, select, input, and buttons.
    const checkbox = preferences.getByRole('checkbox', { name: 'Developer mode (required)' })
    await checkbox.focus()
    await page.keyboard.press('Space')
    assert.equal(await checkbox.isChecked(), true)
    await page.keyboard.press('Tab')
    assert.equal(await select.evaluate(el => el === document.activeElement), true)
    await page.keyboard.press('ArrowDown')
    assert.equal(await select.inputValue(), '1')
    assert.equal(await select.locator('option:checked').innerText(), 'persist')
    await preferences.getByRole('button', { name: 'Save changes', exact: true }).focus()
    await page.keyboard.press('Enter')
    await preferences.getByText('No changes', { exact: true }).waitFor()
    assert.equal(await checkbox.isChecked(), true)
    assert.equal(await select.inputValue(), '1')
    await input.focus()
    await page.keyboard.press('ControlOrMeta+A')
    await page.keyboard.type('')
    await input.fill('')
    assert.equal(await input.getAttribute('aria-invalid'), 'true')
    const errorDescription = await input.evaluate(el => el.getAttribute('aria-describedby').split(' ').map(id => document.getElementById(id)?.textContent).join(' '))
    assert.match(errorDescription, /Text length is outside/)
    assert.equal(await connections.getByRole('button', { name: 'Save changes', exact: true }).isDisabled(), true)
    await input.fill('http://edited.example')
    await page.getByRole('checkbox', { name: 'Reject saves in the demo host' }).check()
    await connections.getByRole('button', { name: 'Save changes', exact: true }).click()
    await connections.getByRole('alert').waitFor()
    assert.equal(await input.inputValue(), 'http://edited.example')
    assert.match(await connections.innerText(), /Unsaved changes/)
    await page.getByRole('checkbox', { name: 'Reject saves in the demo host' }).uncheck()
    await connections.getByRole('button', { name: 'Save changes', exact: true }).click()
    await connections.getByText('No changes', { exact: true }).waitFor()
    await connections.getByRole('button', { name: 'Remove override for Nanite API URL', exact: true }).click()
    assert.equal(await input.isDisabled(), true)
    await connections.getByRole('button', { name: 'Remove staged overrides', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await input.inputValue(), 'http://127.0.0.1:8090')
    assert.equal(await connections.getByRole('button', { name: 'Remove override for Nanite API URL' }).count(), 0)
    const token = page.getByLabel('API token (required)', { exact: true })
    assert.equal(await token.inputValue(), '')
    assert.equal(await token.getAttribute('type'), 'password')
    await secretForm.getByText(/Secret is set/).waitFor()
    assert.equal(await secretForm.getByRole('button', { name: 'Save changes', exact: true }).isDisabled(), true)
    await token.fill('ephemeral-demo-replacement')
    await secretForm.getByRole('button', { name: 'Save changes', exact: true }).click()
    assert.equal(await token.inputValue(), '')
    // Read-only negative: real user input is rejected; forced DOM events cannot cause a save.
    const locked = page.getByLabel('Listen address (required)', { exact: true })
    assert.equal(await locked.isDisabled(), true)
    const before = await locked.inputValue()
    let rejected = false
    try { await locked.fill('attempted-write', { timeout: 300 }) } catch { rejected = true }
    assert.equal(rejected, true)
    assert.equal(await locked.inputValue(), before)
    assert.equal(await deployment.getByRole('button').count(), 0)
    const saveCount = await page.getByText(/^Host save count:/).innerText()
    await deployment.evaluate(el => el.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })))
    assert.equal(await page.getByText(/^Host save count:/).innerText(), saveCount)
    const lockedDescription = await locked.evaluate(el => el.getAttribute('aria-describedby').split(' ').map(id => document.getElementById(id)?.textContent).join(' '))
    assert.match(lockedDescription, /Managed by deployment configuration/)
    const aria = await page.locator('main').ariaSnapshot()
    assert.match(aria, /form "Deployment configuration"/)
    assert.match(aria, /combobox "Tool stream behavior \(required\)"/)
    assert.match(aria, /textbox "Listen address \(required\)" \[disabled\]/)
    assert.match(aria, /checkbox "Developer mode \(required\)" \[checked\]/)
    const bounds = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }))
    assert.ok(bounds.scroll <= bounds.viewport)
    assert.deepEqual(errors, [])
    results.push({ width, styles, saveStyle, selectFontSize: '13px', panelRadius: '10px', bounds, keyboard: 'checkbox Space, select ArrowDown, Tab order, Save/Reset Enter', aria, errorDescription, lockedDescription, rejectedSaveRetainsDraft: true, hostSuccess: true, secretReplacementClearedByHost: true, readOnlyInputRejected: rejected, readOnlyProgrammaticSubmitSaved: false, pageErrors: errors })
    await page.close()
  }
  const receipt = { fixture: 'packages/kit-settings/demo', engine: browser.version(), accessibilityScope: 'Browser accessibility tree, labels/descriptions/required/invalid/disabled/status/alert and real keyboard actions; no live screen-reader speech tested.', results }
  if (process.argv[2]) await writeFile(process.argv[2], JSON.stringify(receipt, null, 2) + '\n')
  console.log(JSON.stringify(receipt, null, 2))
} finally { await browser.close() }
