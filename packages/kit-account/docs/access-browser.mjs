import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true })
const results = []
try {
  for (const width of [1280, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.goto(process.env.FIXTURE_URL || 'http://127.0.0.1:18753')
    const manager = page.getByRole('region', { name: 'API tokens', exact: true })
    const connections = page.getByRole('region', { name: 'Connected accounts', exact: true })
    const longName = `Browser fixture ${'long-name-'.repeat(16)}`
    await page.getByLabel('Token name', { exact: true }).fill(longName)
    assert.equal(await page.getByRole('button', { name: 'Create token', exact: true }).isDisabled(), true)
    await page.getByRole('checkbox', { name: 'Read', exact: true }).check()
    await page.getByRole('button', { name: 'Fail creation', exact: true }).click()
    await page.getByRole('button', { name: 'Create token', exact: true }).click()
    assert.equal(await page.getByLabel('Token name', { exact: true }).isDisabled(), true)
    await manager.getByRole('alert').waitFor()
    assert.equal(await page.getByLabel('Token name', { exact: true }).inputValue(), longName)
    assert.equal(await page.getByRole('region', { name: 'Save your new token' }).count(), 0, 'failure discloses no token')
    await page.getByRole('button', { name: 'Allow creation', exact: true }).click()
    await page.getByRole('button', { name: 'Create token', exact: true }).click()
    const disclosure = page.getByRole('region', { name: 'Save your new token' })
    await disclosure.waitFor()
    const exposed = await disclosure.locator('code').innerText()
    assert.equal((await manager.innerText()).includes(exposed), false, 'ordinary list is metadata only')
    await page.getByRole('button', { name: 'Copy token', exact: true }).click()
    await page.getByRole('button', { name: 'Copied', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), exposed)
    const revealBounds = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }))
    assert.ok(revealBounds.scroll <= revealBounds.viewport, 'long token/name wrap in narrow view')
    await page.getByRole('button', { name: 'I have saved this token', exact: true }).click()
    assert.equal(await disclosure.count(), 0)
    assert.equal((await page.locator('body').innerText()).includes(exposed), false, 'dismissed value leaves DOM')
    assert.deepEqual(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length })), { local: 0, session: 0 })
    await page.evaluate(() => navigator.clipboard.writeText('')) // Clear the synthetic fixture clipboard.

    assert.equal(await manager.getByRole('button', { name: 'Revoke Unsupported state' }).count(), 0)
    const revoke = manager.getByRole('button', { name: `Revoke ${longName}`, exact: true })
    await revoke.click()
    const dialog = page.getByRole('dialog', { name: 'Revoke API token?' })
    await dialog.waitFor()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await revoke.count(), 1, 'cancel does not revoke')
    await page.getByRole('button', { name: 'Fail revocation', exact: true }).click()
    await revoke.click()
    await dialog.getByRole('button', { name: 'Revoke token', exact: true }).click()
    await dialog.getByRole('alert').waitFor()
    assert.equal(await dialog.isVisible(), true, 'failed revoke stays open')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Allow revocation', exact: true }).click()
    await revoke.click()
    await dialog.getByRole('button', { name: 'Revoke token', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await revoke.count(), 0, 'host success removes revoke action')
    await manager.getByText('revoked', { exact: true }).waitFor()

    assert.equal(await connections.getByRole('button', { name: /Unknown provider/ }).count(), 0)
    await page.getByRole('button', { name: 'Fail connection', exact: true }).click()
    await connections.getByRole('button', { name: 'Connect Mail', exact: true }).click()
    await connections.getByText('Connecting…', { exact: true }).waitFor()
    assert.equal(await connections.getByRole('button', { name: 'Connect Mail', exact: true }).count(), 0)
    await connections.getByRole('alert').waitFor()
    await page.getByRole('button', { name: 'Allow connection', exact: true }).click()
    await connections.getByRole('button', { name: 'Connect Mail', exact: true }).click()
    await connections.getByText('Fixture mail', { exact: true }).waitFor()
    await connections.getByRole('button', { name: 'Disconnect Mail', exact: true }).click()
    const disconnectDialog = page.getByRole('dialog', { name: 'Disconnect provider?' })
    await disconnectDialog.getByRole('button', { name: 'Disconnect provider', exact: true }).click()
    await disconnectDialog.waitFor({ state: 'hidden' })
    await connections.getByRole('button', { name: 'Connect Mail', exact: true }).waitFor()

    // A context switch must drop an undisclosed create response and cancel old work.
    await page.getByLabel('Token name', { exact: true }).fill('Second fixture')
    await page.getByRole('checkbox', { name: 'Read', exact: true }).check()
    await page.getByRole('button', { name: 'Create token', exact: true }).click()
    await disclosure.waitFor()
    await page.getByRole('button', { name: 'Switch account context', exact: true }).click()
    await page.getByText('Fixture context 2', { exact: true }).waitFor()
    assert.equal(await disclosure.count(), 0, 'context reset drops secret')
    assert.equal(await page.getByLabel('Token name', { exact: true }).inputValue(), '')
    await page.getByLabel('Token name', { exact: true }).fill('Canceled create')
    await page.getByRole('checkbox', { name: 'Read', exact: true }).check()
    await page.getByRole('button', { name: 'Create token', exact: true }).click()
    await page.getByRole('button', { name: 'Switch account context', exact: true }).click()
    await page.getByText('Fixture context 3', { exact: true }).waitFor()
    await page.waitForTimeout(450)
    assert.equal(await disclosure.count(), 0, 'old pending create cannot disclose in a new context')
    assert.deepEqual(errors, [])
    if (width === 390 && process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH })
    results.push({ width, controlledCreateScopes: true, failedCreateRetainsDraft: true, oneTimeDisclosure: true, explicitCopy: true, secretRemovedOnDismissAndContextChange: true, staleCreateCanceled: true, browserStorageEntries: 0, confirmedRevokeAndRetry: true, providerConnectRetryAndDisconnect: true, unknownStatesReadOnly: true, revealBounds, pageErrors: errors })
    await context.close()
  }
  const receipt = { fixture: 'packages/kit-account/demo/access.tsx', credentials: 'synthetic only; values intentionally omitted from receipts/screenshots', results }
  if (process.argv[2]) await writeFile(process.argv[2], `${JSON.stringify(receipt, null, 2)}\n`)
  console.log(JSON.stringify(receipt, null, 2))
} finally { await browser.close() }
