import { readFileSync, writeFileSync } from 'node:fs'
import { BUILTIN_THEMES, emitThemeCss } from '@hollis-labs/design-tokens'

// The kit owns legacy IDs; design-tokens owns every palette value and mode rule.
const aliases = JSON.parse(readFileSync(new URL('../src/styles/legacy-themes.json', import.meta.url), 'utf8'))
const output = ['/* GENERATED by kit-dashboard scripts/generate-theme-aliases.mjs.',
  ' * Palette values and mode selectors come from design-tokens emitThemeCss.',
  ' * Legacy ID mapping: src/styles/legacy-themes.json. Do not hand-edit values.',
  ' */', '']
for (const [legacy, canonical] of Object.entries(aliases)) {
  const theme = BUILTIN_THEMES.find((candidate) => candidate.id === canonical)
  if (!theme) throw new Error(`Unknown canonical dashboard theme: ${canonical}`)
  output.push(emitThemeCss({ ...theme, id: legacy }, { asDefault: legacy === 'p4-white' }))
}
writeFileSync(new URL('../src/styles/legacy-themes.css', import.meta.url), output.join('\n'))
console.log('Generated dashboard legacy theme aliases from design-tokens')
